def split_args(text):
    if text.strip() == "void" or not text.strip():
        return []
    args = []
    depth = 0
    start = 0
    for i, char in enumerate(text):
        if char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
        elif char == "," and depth == 0:
            args.append(text[start:i].strip())
            start = i + 1
    args.append(text[start:].strip())
    return args


def parse_signature(signature):
    match = re.fullmatch(r"(.+?)\s+(MPI_[A-Za-z0-9_]+)\((.*)\)", signature)
    if not match:
        raise ValueError(f"cannot parse function signature: {signature}")
    return match.group(1), match.group(2), split_args(match.group(3))


def wrapper_type(text):
    text = re.sub(r"\bMPI_Status\b", "MPI_Status", text)
    text = re.sub(r"\bMPI_Fint\b", "std::int32_t", text)
    return text


def function_wrapper_name(name):
    return "mpiwrap_" + name.removeprefix("MPI_")


def constant_return_type(name, category):
    if category == "provider_handle":
        if name.startswith("MPI_COMM_"):
            return "MPI_Comm"
        if name.startswith("MPI_GROUP_"):
            return "MPI_Group"
        if name.startswith("MPI_REQUEST_"):
            return "MPI_Request"
        if name.startswith("MPI_OP_") or name in {
                "MPI_SUM", "MPI_PROD", "MPI_MAX", "MPI_MIN", "MPI_MAXLOC", "MPI_MINLOC",
                "MPI_LAND", "MPI_BAND", "MPI_LOR", "MPI_BOR", "MPI_LXOR", "MPI_BXOR"}:
            return "MPI_Op"
        if name.startswith("MPI_ERRHANDLER_") or name in {"MPI_ERRORS_ARE_FATAL", "MPI_ERRORS_RETURN"}:
            return "MPI_Errhandler"
        return "MPI_Datatype"
    if category in {"provider_integer", "compile_time_integer"}:
        return "std::int32_t"
    if category == "buffer_sentinel":
        return "void *"
    if category == "status_sentinel":
        return "MPI_Status *"
    raise ValueError(f"unknown constant class: {category}")


