def generate(output, write=True):
    args_doc = json.loads((DEVELOPMENT / "argument-metadata.json").read_text())
    constants_doc = json.loads((DEVELOPMENT / "constant-metadata.json").read_text())
    types_doc = json.loads((DEVELOPMENT / "type-metadata.json").read_text())
    versions_doc = json.loads((DEVELOPMENT / "signature-versions.json").read_text())
    with (DEVELOPMENT / "thread-mpi-api.tsv").open(newline="") as stream:
        api_rows = list(csv.DictReader(stream, delimiter="\t"))
    functions = args_doc["functions"]
    constants = constants_doc["constants"]
    version_records = versions_doc["signature_versions"]
    names = {function["name"] for function in functions}
    if set(version_records) != names:
        raise ValueError("signature-versions.json must contain exactly one record per function")
    versions = {}
    for function in functions:
        name = function["name"]
        record = version_records[name]
        if not isinstance(record, dict) or not isinstance(record.get("version"), int) or record["version"] < 1:
            raise ValueError(f"{name}: signature version must be a positive integer")
        fingerprint = canonical_signature_fingerprint(function["signature"])
        if record.get("canonical_type_sha256") != fingerprint:
            raise ValueError(f"{name}: canonical signature changed; update signature version and fingerprint")
        versions[name] = record["version"]
    api_symbols = {row["symbol"] for row in api_rows}
    for function in functions:
        route = function.get("provider_routes", {}).get("internal_thread_mpi", {})
        symbol = route.get("symbol")
        if route.get("status") == "direct" and symbol not in api_symbols:
            raise ValueError(f"{function['name']}: direct tMPI symbol {symbol} absent from stable API inventory")
    abi = (DEVELOPMENT / "provider-abi-proposal.h").read_text()
    abi = abi.replace("/* Review-only C-compatible proposal. This file is not installed or included by PLUMED. */",
                      "/* Generated by tools/generate.py from the reviewed provider ABI contract. */")
    native_rows, thread_rows = render_adapter_entries(functions, versions)
    files = {
        "mpiwrap.h": render_header(functions, types_doc["types"], constants),
        "mpiwrap-pointers.h": render_pointers(functions, constants),
        "callback-bridges.h": render_callback_bridges(),
        "provider-abi.h": abi,
        "provider-callbacks.h": render_provider_callbacks(functions),
        "thread-mpi-availability.h": render_thread_mpi_availability(functions),
        "native-adapter-entries.inc": native_rows,
        "signature-ids.tsv": "function\tsignature_id\tsignature_version\tcanonical_type_sha256\n" + "".join(
            f"{function['name']}\t0x{int(hashlib.sha256(function['name'].encode('ascii')).hexdigest()[:8], 16):08x}\t{versions[function['name']]}\t{canonical_signature_fingerprint(function['signature'])}\n"
            for function in functions),
        "thread-mpi-adapter-entries.inc": thread_rows,
        "thread-mpi-symbol-check.cpp": render_thread_symbol_checks(functions),
        "native-signature-check.cpp": render_native_signature_checks(functions),
        "wrapper-header-check.cpp": render_wrapper_header_check(),
        "native-header-check.cpp": render_native_header_check(),
        "native-entry-check.cpp": render_native_entry_check(),
        "thread-mpi-entry-check.cpp": render_thread_entry_check(),
        "coverage.tsv": render_coverage(functions),
        "support-matrix.md": render_matrix(functions, constants_doc["constants"], types_doc["types"]),
    }
    # Generated C/C++ files follow project style using the checked-in formatter,
    # independent of the generated output directory (including --check temp trees).
    astyle = ROOT / "astyle/astyle"
    options = ROOT / ".astyle.options"
    if not astyle.exists() or not options.is_file():
        raise RuntimeError(f"generated code formatting requires {astyle} and {options}")
    for name, text in list(files.items()):
        if pathlib.Path(name).suffix in {".h", ".cpp", ".inc"}:
            files[name] = subprocess.check_output(
                [str(astyle), f"--options={options}"], input=text.encode()).decode()
    if write:
        output.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (output / name).write_text(text)
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    import subprocess
    subprocess.run([sys.executable, str(DEVELOPMENT / "validate-manifest.py")], check=True)
    expected = generate(args.output, write=not args.check)
    if args.check:
        bad = [name for name, text in expected.items()
               if not (args.output / name).is_file() or
               (args.output / name).read_text() != text]
        if bad:
            raise SystemExit("generated files differ: " + ", ".join(bad))
    count = len(json.loads((DEVELOPMENT / "argument-metadata.json").read_text())["functions"])
    action = "verified" if args.check else "generated"
    print(f"{action} {len(expected)} files for {count} MPI functions")


if __name__ == "__main__":
    main()
