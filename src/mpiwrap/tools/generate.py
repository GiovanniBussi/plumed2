def native_function_pointer_type(signature):
    result, name, args = parse_signature(signature)
    params = []
    for argument in args:
        if argument == "...":
            params.append("...")
            continue
        array = re.search(r"([A-Za-z_]\w*)\s*((?:\[[^]]*\])+)$", argument)
        if array:
            base = argument[:array.start()].strip()
            dimensions = re.findall(r"\[([^]]*)\]", array.group(2))
            if len(dimensions) == 1:
                params.append(base + " *")
            else:
                params.append(base + " (*)" + "".join("[" + dim + "]" for dim in dimensions[1:]))
            continue
        name_match = re.search(r"([A-Za-z_]\w*)\s*$", argument)
        if not name_match:
            raise ValueError(f"cannot parse native parameter {argument!r}")
        params.append(argument[:name_match.start()].rstrip())
    return name, f"{result} (*)({', '.join(params) if params else 'void'})"


def render_native_signature_checks(functions):
    lines = ["// Generated by tools/generate.py; compile with each native MPI header.",
             "#include <mpi.h>", "#include <type_traits>"]
    for function in functions:
        name, expected = native_function_pointer_type(function["signature"])
