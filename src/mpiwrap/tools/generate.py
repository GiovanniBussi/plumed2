def name_argument(declaration):
    match = re.search(r"([A-Za-z_]\w*)\s*(?:\[[^]]*\]\s*)*$", declaration)
    if not match:
        raise ValueError(f"cannot identify argument name in {declaration!r}")
    return match.group(1)



def provider_argument(declaration):
    if declaration == "...":
        return declaration
    match = re.search(r"([A-Za-z_]\w*)\s*((?:\[[^]]*\]\s*)*)$", declaration)
    if not match:
        raise ValueError(f"cannot parse provider argument: {declaration!r}")
    name, array_suffix = match.groups()
    base = declaration[:match.start()].rstrip()
    replacements = [
        (r"\bMPI_User_function\s*\*", "plumed_mpiw_user_function_fn "),
        (r"\bMPI_Comm_errhandler_function\s*\*", "plumed_mpiw_comm_errhandler_function_fn "),
        (r"\bMPI_Status\b", "plumed_mpiw_status"),
        (r"\bMPI_(?:Comm|Datatype|Errhandler|Group|Op|Request)\b", "plumed_mpiw_handle_storage"),
        (r"\bMPI_Fint\b", "int32_t"),
        (r"\bint\b", "int32_t"),
    ]
    for pattern, replacement in replacements:
        base = re.sub(pattern, replacement, base)
    return f"{base} {name}{array_suffix}"


def provider_result(result):
    if result == "int":
        return "int32_t"
    if result in HANDLES:
        return "plumed_mpiw_handle_storage"
    return result


def render_provider_callbacks(functions):
    lines = ["// Generated by tools/generate.py; do not edit.",
             "#ifndef PLUMED_MPIWRAP_GENERATED_PROVIDER_CALLBACKS_H",
             "#define PLUMED_MPIWRAP_GENERATED_PROVIDER_CALLBACKS_H",
             '#include "provider-abi.h"', "#include <stdint.h>",
             "#ifdef __cplusplus", 'extern "C" {', "#endif",
             "typedef void (*plumed_mpiw_user_callback_invoke_fn)(plumed_mpiw_generic_fn, void *, void *, int32_t, plumed_mpiw_handle_storage);",
             "typedef struct { plumed_mpiw_generic_fn function; plumed_mpiw_user_callback_invoke_fn invoke; } plumed_mpiw_user_callback;",
             "typedef void (*plumed_mpiw_comm_errhandler_invoke_fn)(plumed_mpiw_generic_fn, plumed_mpiw_handle_storage, int32_t);",
             "typedef struct { plumed_mpiw_generic_fn function; plumed_mpiw_comm_errhandler_invoke_fn invoke; } plumed_mpiw_comm_errhandler_callback;"]
    for function in functions:
        if function.get("provider_routes", {}).get("injected_real_mpi", {}).get("status") == "unavailable":
            continue
        result, name, raw_args = parse_signature(function["signature"])
        if name == "MPI_Op_create":
            args = ["plumed_mpiw_user_callback *", "int32_t", "plumed_mpiw_handle_storage *"]
        elif name == "MPI_Comm_create_errhandler":
            args = ["plumed_mpiw_comm_errhandler_callback *", "plumed_mpiw_handle_storage *"]
        else:
            args = [provider_argument(arg) for arg in raw_args]
        if not args:
            args = ["void"]
        lines.append(f"typedef {provider_result(result)} (*plumed_mpiw_{name}_fn)({', '.join(args)});")
    lines += ['#ifdef __cplusplus', "}", "#endif", "#endif"]
    return "\n".join(lines) + "\n"


